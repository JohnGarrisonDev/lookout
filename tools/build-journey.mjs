// Dev tool: grow the 40 Journey boards from the recipes in src/logic/levels.js and write src/logic/journey-data.js.
//   node tools/build-journey.mjs          print the boards (dry run)
//   node tools/build-journey.mjs --write  also write the data file
// Only re-run this for NEW levels. Re-rolling existing ones changes boards players have stars on.
import { writeFileSync } from 'node:fs'
import { hashString } from '../kit/kit.js'
import { RECIPES, levelLabel } from '../src/logic/levels.js'
import { generate } from '../src/logic/generate.js'
import { encodeBoard } from '../src/logic/rules.js'
import { maskOf, countSolutions, bit, TECHS, TIER } from '../src/logic/solver.js'

const out = []
RECIPES.forEach((r, i) => {
  for (let k = 0; ; k++) {
    const allow = r.allow ? maskOf(r.allow) : 0, need = r.need ? maskOf(r.need) : 0
    const p = generate({ size: r.size, band: r.band, allow, need, hedges: r.hedges, seed: hashString(`lookout/journey/${i + 1}/${k}`) })
    // gentle boards have no "band" technique, so check `need` here; skip boards that lean on a tier-1 rule only once in tutorials
    const ok = p.inBand && (p.grade.used & need) === need && (r.hedges ? p.sol.reduce((a, v) => a + v, 0) === r.hedges : true)
    if (!ok) continue
    if (countSolutions(p).count !== 1) throw new Error('not unique: ' + encodeBoard(p))
    const used = TECHS.filter((t) => p.grade.used & bit(t)).map((t) => `${t}:${p.grade.counts[t]}`).join(' ')
    const clues = p.clues.reduce((a, v) => a + (v > 0 ? 1 : 0), 0)
    console.log(`${levelLabel(i).padEnd(5)} ${r.size}x${r.size} ${r.band.padEnd(7)} try ${k}  lookouts ${String(clues).padStart(2)}  score ${String(p.grade.score).padStart(3)}  ${used}`)
    out.push(encodeBoard(p))
    break
  }
})
void TIER
if (process.argv.includes('--write')) {
  const body = `// Generated by tools/build-journey.mjs. Do not edit by hand.\n// One string per level: rows joined by "/", "#" hedge (the answer), "." open tile, base-36 digit = a lookout's number.\nexport const JOURNEY = [\n${out.map((s) => `  '${s}',`).join('\n')}\n]\n`
  writeFileSync(new URL('../src/logic/journey-data.js', import.meta.url), body)
  console.log('wrote src/logic/journey-data.js')
}
